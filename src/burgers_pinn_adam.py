def ensure_reference_dataset():
    """
    Download Burgers.npz if it does not exist.
    Verify that x, t and usol arrays are present.
    """

    if not REFERENCE_PATH.exists():
        temporary_path = REFERENCE_PATH.with_suffix(".download")

        print("\nReference dataset not found.")
        print("Downloading Burgers.npz from Wu et al.'s repository...")

        request = urllib.request.Request(
            REFERENCE_URL,
            headers={
                "User-Agent": "PINN-Burgers-Research-Study"
            },
        )

        try:
            with urllib.request.urlopen(
                request, timeout=60
            ) as response:
                temporary_path.write_bytes(response.read())

            # Validate the downloaded archive before accepting it.
            with np.load(
                temporary_path, allow_pickle=False
            ) as data:
                required = {"x", "t", "usol"}

                missing = required.difference(data.files)

                if missing:
                    raise ValueError(
                        f"Missing required arrays: {missing}"
                    )

                x = np.asarray(data["x"]).reshape(-1)
                t = np.asarray(data["t"]).reshape(-1)
                usol = np.asarray(data["usol"])

                valid_shapes = {
                    (len(x), len(t)),
                    (len(t), len(x)),
                }

                if usol.shape not in valid_shapes:
                    raise ValueError(
                        f"Unexpected usol shape: {usol.shape}"
                    )

            temporary_path.replace(REFERENCE_PATH)

            print("Reference dataset downloaded successfully.")

        except Exception as exc:
            if temporary_path.exists():
                temporary_path.unlink()

            raise RuntimeError(
                "Unable to download the reference dataset.\n"
                f"URL: {REFERENCE_URL}\n"
                "Check your internet connection."
            ) from exc

    # Validate the local copy as well.
    with np.load(
        REFERENCE_PATH, allow_pickle=False
    ) as data:
        required = {"x", "t", "usol"}
        missing = required.difference(data.files)

        if missing:
            raise ValueError(
                f"Reference file is missing arrays: {missing}"
            )

        x = np.asarray(data["x"]).reshape(-1)
        t = np.asarray(data["t"]).reshape(-1)
        usol = np.asarray(data["usol"])

        if usol.shape not in {
            (len(x), len(t)),
            (len(t), len(x)),
        }:
            raise ValueError(
                f"Unexpected reference shape: {usol.shape}"
            )

    print("Reference file:", REFERENCE_PATH)
    print("Spatial points:", len(x))
    print("Time points:", len(t))
    print("Reference array shape:", usol.shape)

    return REFERENCE_PATH


# ============================================================
# 3. NEURAL NETWORK
# ============================================================

class BurgersPINN(nn.Module):
    """
    Input: [t, x]
    Output: predicted velocity u_theta(t, x)
    """

    def __init__(self, width=WIDTH, depth=DEPTH):
        super().__init__()

        layers = []
        input_size = 2

        # Hidden layers.
        for _ in range(depth):
            layers.append(
                nn.Linear(input_size, width)
            )
            layers.append(nn.Tanh())

            input_size = width

        # Final layer: one output, u.
        layers.append(nn.Linear(width, 1))

        self.network = nn.Sequential(*layers)

    def forward(self, tx):
        return self.network(tx)


# ============================================================
# 4. GENERATE TRAINING POINTS
# ============================================================

def generate_training_points():

    # --------------------------------------------------------
    # PDE collocation points
    # --------------------------------------------------------
    x_f = (
        -1.0
        + 2.0 * torch.rand(
            N_F, 1, device=DEVICE, dtype=DTYPE
        )
    )

    t_f = torch.rand(
        N_F, 1, device=DEVICE, dtype=DTYPE
    )

    # Input order is [t, x].
    tx_f = torch.cat((t_f, x_f), dim=1)

    # --------------------------------------------------------
    # Initial condition: u(x, 0) = -sin(pi*x)
    # --------------------------------------------------------
    x_ic = (
        -1.0
        + 2.0 * torch.rand(
            N_IC, 1, device=DEVICE, dtype=DTYPE
        )
    )

    t_ic = torch.zeros_like(x_ic)

    tx_ic = torch.cat((t_ic, x_ic), dim=1)

    u_ic = -torch.sin(math.pi * x_ic)

    # --------------------------------------------------------
    # Boundary conditions: u(-1,t) = u(1,t) = 0
    # --------------------------------------------------------
    t_bc = torch.rand(
        N_BC_PER_SIDE, 1,
        device=DEVICE, dtype=DTYPE
    )

    x_left = -torch.ones_like(t_bc)
    x_right = torch.ones_like(t_bc)

    tx_left = torch.cat((t_bc, x_left), dim=1)
    tx_right = torch.cat((t_bc, x_right), dim=1)

    tx_bc = torch.cat(
        (tx_left, tx_right), dim=0
    )

    u_bc = torch.zeros(
        2 * N_BC_PER_SIDE, 1,
        device=DEVICE, dtype=DTYPE
    )

    return tx_f, tx_ic, u_ic, tx_bc, u_bc


# ============================================================
# 5. AUTOMATIC DIFFERENTIATION AND PDE RESIDUAL
# ============================================================

def burgers_residual(model, tx_points):
    """
    Compute:
        R = u_t + u*u_x - nu*u_xx
    """

    # Make a differentiable copy of input coordinates.
    tx = (
        tx_points.detach()
        .clone()
        .requires_grad_(True)
    )

    # Neural network prediction.
    u = model(tx)

    # First derivatives with respect to [t, x].
    first_derivatives = torch.autograd.grad(
        outputs=u,
        inputs=tx,
        grad_outputs=torch.ones_like(u),
        create_graph=True,
    )[0]

    u_t = first_derivatives[:, 0:1]
    u_x = first_derivatives[:, 1:2]

    # Second derivative with respect to x.
    second_derivatives = torch.autograd.grad(
        outputs=u_x,
        inputs=tx,
        grad_outputs=torch.ones_like(u_x),
        create_graph=True,
    )[0]

    u_xx = second_derivatives[:, 1:2]

    # Burgers equation residual.
    residual = u_t + u * u_x - NU * u_xx

    return residual


# ============================================================
# 6. TRAIN THE VANILLA PINN
# ============================================================

def train():

    model = BurgersPINN().to(
        device=DEVICE, dtype=DTYPE
    )

    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=LEARNING_RATE,
    )

    (
        tx_f,
        tx_ic,
        u_ic,
        tx_bc,
        u_bc,
    ) = generate_training_points()

    history = []

    start_time = time.time()

    print("\nStarting vanilla Burgers PINN training...")

    for step in range(1, ADAM_STEPS + 1):

        optimizer.zero_grad(set_to_none=True)

        # PDE loss.
        residual = burgers_residual(model, tx_f)
        loss_pde = torch.mean(residual ** 2)

        # Initial-condition loss.
        prediction_ic = model(tx_ic)
        loss_ic = torch.mean(
            (prediction_ic - u_ic) ** 2
        )

        # Boundary-condition loss.
        prediction_bc = model(tx_bc)
        loss_bc = torch.mean(
            (prediction_bc - u_bc) ** 2
        )

        # Total loss.
        loss_total = loss_pde + loss_ic + loss_bc

        # Backpropagation.
        loss_total.backward()

        # Update network parameters.
        optimizer.step()

        # Record the losses.
        if (
            step % LOG_EVERY == 0
            or step == 1
            or step == ADAM_STEPS
        ):
            row = [
                step,
                loss_total.item(),
                loss_pde.item(),
                loss_ic.item(),
                loss_bc.item(),
            ]

            history.append(row)

            print(
                f"Step {step:5d} | "
                f"Total {loss_total.item():.4e} | "
                f"PDE {loss_pde.item():.4e} | "
                f"IC {loss_ic.item():.4e} | "
                f"BC {loss_bc.item():.4e}"
            )

    elapsed = time.time() - start_time

    # Save model and configuration.
    model_path = (
        RESULTS_DIR / "burgers_vanilla_model.pt"
    )

    torch.save(
        {
            "model_state_dict": model.state_dict(),
            "width": WIDTH,
            "depth": DEPTH,
            "nu": NU,
            "input_order": ["t", "x"],
            "seed": SEED,
            "adam_steps": ADAM_STEPS,
            "learning_rate": LEARNING_RATE,
            "N_F": N_F,
            "N_IC": N_IC,
            "N_BC_PER_SIDE": N_BC_PER_SIDE,
        },
        model_path,
    )

    # Save loss history.
    history_array = np.asarray(
        history, dtype=np.float64
    )

    history_path = (
        RESULTS_DIR / "training_history.csv"
    )

    np.savetxt(
        history_path,
        history_array,
        delimiter=",",
        header="step,total_loss,pde_loss,ic_loss,bc_loss",
        comments="",
    )

    # Plot loss history.
    plt.figure(figsize=(8, 5))

    for column, label in zip(
        range(1, 5),
        ["Total", "PDE", "IC", "BC"],
    ):
        plt.semilogy(
            history_array[:, 0],
            np.maximum(
                history_array[:, column], 1e-16
            ),
            label=label,
        )

    plt.xlabel("Training step")
    plt.ylabel("Mean squared error loss")
    plt.title("Vanilla Burgers PINN: Training losses")
    plt.legend()
    plt.tight_layout()

    loss_plot = (
        RESULTS_DIR / "training_losses.png"
    )

    plt.savefig(loss_plot, dpi=200)
    plt.show()
    plt.close()

    print(f"\nTraining time: {elapsed:.2f} seconds")
    print("Model saved:", model_path)
    print("History saved:", history_path)
    print("Loss plot saved:", loss_plot)

    return model


