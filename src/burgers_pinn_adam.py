# 7. EVALUATE AGAINST THE REFERENCE SOLUTION
# ============================================================

def evaluate_reference(model):

    try:
        dataset_path = ensure_reference_dataset()

    except Exception as exc:
        print("\nReference evaluation was skipped.")
        print("Reason:", exc)
        print(
            "Training has completed, but no reference-based "
            "error can be reported without the dataset."
        )
        return

    with np.load(
        dataset_path, allow_pickle=False
    ) as data:
        x = np.asarray(data["x"]).reshape(-1)
        t = np.asarray(data["t"]).reshape(-1)
        usol_raw = np.asarray(data["usol"])

    # Standardize reference orientation to (time, space).
    if usol_raw.shape == (len(x), len(t)):
        u_reference = usol_raw.T

    elif usol_raw.shape == (len(t), len(x)):
        u_reference = usol_raw

    else:
        raise ValueError(
            f"Cannot orient usol shape {usol_raw.shape}"
        )

    # Create every (t, x) evaluation pair.
    X, T = np.meshgrid(x, t, indexing="xy")

    tx_eval = np.column_stack(
        (T.ravel(), X.ravel())
    )

    model.eval()

    predictions = []

    # Evaluate in batches.
    # Gradients are not needed for solution comparison.
    with torch.no_grad():

        chunk_size = 8192

        for start in range(
            0, tx_eval.shape[0], chunk_size
        ):
            tx_chunk = torch.as_tensor(
                tx_eval[start:start + chunk_size],
                dtype=DTYPE,
                device=DEVICE,
            )

            predictions.append(
                model(tx_chunk).cpu().numpy()
            )

    u_prediction = np.concatenate(
        predictions, axis=0
    ).reshape(len(t), len(x))

    # Difference between PINN and reference.
    error = u_prediction - u_reference

    # Relative L2 error.
    reference_l2 = np.linalg.norm(
        u_reference.ravel()
    )

    # Relative Linfinity error.
    reference_linf = np.max(
        np.abs(u_reference)
    )

    if reference_l2 == 0 or reference_linf == 0:
        raise ValueError(
            "Reference norm is zero; relative errors are undefined."
        )

    relative_l2 = (
        np.linalg.norm(error.ravel())
        / reference_l2
    )

    relative_linf = (
        np.max(np.abs(error))
        / reference_linf
    )

    max_absolute_error = np.max(
        np.abs(error)
    )

    print("\n===== REFERENCE EVALUATION =====")
    print("Dataset:", dataset_path)
    print("Spatial points:", len(x))
    print(
        f"Time points: {len(t)} "
        f"(from {t.min():.4f} to {t.max():.4f})"
    )
    print(f"Relative L2 error:      {relative_l2:.6e}")
    print(f"Relative Linf error:    {relative_linf:.6e}")
    print(
        f"Maximum absolute error: "
        f"{max_absolute_error:.6e}"
    )

    # Save reference, prediction and error.
    evaluation_path = (
        RESULTS_DIR / "reference_evaluation.npz"
    )

    np.savez_compressed(
        evaluation_path,
        x=x,
        t=t,
        u_reference=u_reference,
        u_prediction=u_prediction,
        error=error,
    )

    # Compare spatial profiles at the last reference time.
    final_index = int(np.argmax(t))

    plt.figure(figsize=(8, 5))

    plt.plot(
        x,
        u_reference[final_index],
        label="Reference",
    )

    plt.plot(
        x,
        u_prediction[final_index],
        "--",
        label="Vanilla PINN",
    )

    plt.xlabel("x")
    plt.ylabel("u(x,t)")
    plt.title(
        f"Solution comparison at t = {t[final_index]:.2f}"
    )
    plt.legend()
    plt.tight_layout()

    comparison_path = (
        RESULTS_DIR / "reference_comparison_final_time.png"
    )

    plt.savefig(comparison_path, dpi=200)
    plt.show()
    plt.close()

    # Plot the absolute error throughout space and time.
    plt.figure(figsize=(8, 5))

    plt.imshow(
        np.abs(error),
        origin="lower",
        aspect="auto",
        extent=[
            x.min(), x.max(),
            t.min(), t.max(),
        ],
    )

    plt.colorbar(label="Absolute error")
    plt.xlabel("x")
    plt.ylabel("t")
    plt.title("Vanilla Burgers PINN: Absolute error field")
    plt.tight_layout()

    error_plot = (
        RESULTS_DIR / "absolute_error_field.png"
    )

    plt.savefig(error_plot, dpi=200)
    plt.show()
    plt.close()

    print("Evaluation data saved:", evaluation_path)
    print("Comparison plot saved:", comparison_path)
    print("Error plot saved:", error_plot)


