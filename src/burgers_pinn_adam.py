"""
B1: Vanilla PyTorch PINN for 1D Burgers equation

PDE:
    u_t + u*u_x - nu*u_xx = 0

Domain:
    x in [-1, 1], t in [0, 1]

Initial condition:
    u(x, 0) = -sin(pi*x)

Boundary conditions:
    u(-1, t) = u(1, t) = 0

Viscosity:
    nu = 0.01/pi

Reference:
    Burgers.npz from the Wu et al. PINN sampling repository.
    Reference data is used ONLY for evaluation, not training.
"""

