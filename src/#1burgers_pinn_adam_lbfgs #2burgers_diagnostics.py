# ============================================================
# 3. NEURAL NETWORK
# ============================================================

class BurgersPINN(nn.Module):
    def __init__(self, width=WIDTH, depth=DEPTH):
        super().__init__()
        layers = []
        input_size = 2
        for _ in range(depth):
            layers.append(nn.Linear(input_size, width))
            layers.append(nn.Tanh())
            input_size = width
        layers.append(nn.Linear(width, 1))
        self.network = nn.Sequential(*layers)

    def forward(self, tx):
        return self.network(tx)

# ============================================================
# 4. GENERATE TRAINING POINTS
# ============================================================

def generate_training_points():
    # PDE collocation points
    x_f = -1.0 + 2.0 * torch.rand(N_F, 1, device=DEVICE, dtype=DTYPE)
    t_f = torch.rand(N_F, 1, device=DEVICE, dtype=DTYPE)
    tx_f = torch.cat((t_f, x_f), dim=1)

    # Initial condition
    x_ic = -1.0 + 2.0 * torch.rand(N_IC, 1, device=DEVICE, dtype=DTYPE)
    t_ic = torch.zeros_like(x_ic)
    tx_ic = torch.cat((t_ic, x_ic), dim=1)
    u_ic = -torch.sin(math.pi * x_ic)

    # Boundary conditions
    t_bc = torch.rand(N_BC_PER_SIDE, 1, device=DEVICE, dtype=DTYPE)
    x_left = -torch.ones_like(t_bc)
    x_right = torch.ones_like(t_bc)
    tx_left = torch.cat((t_bc, x_left), dim=1)
    tx_right = torch.cat((t_bc, x_right), dim=1)
    tx_bc = torch.cat((tx_left, tx_right), dim=0)
    u_bc = torch.zeros(2 * N_BC_PER_SIDE, 1, device=DEVICE, dtype=DTYPE)

    return tx_f, tx_ic, u_ic, tx_bc, u_bc

# ============================================================
# 5. AUTOMATIC DIFFERENTIATION AND PDE RESIDUAL
# ============================================================

def burgers_residual(model, tx_points):
    tx = tx_points.detach().clone().requires_grad_(True)
    u = model(tx)

    first_derivatives = torch.autograd.grad(
        outputs=u, inputs=tx,
        grad_outputs=torch.ones_like(u),
        create_graph=True,
    )[0]

    u_t = first_derivatives[:, 0:1]
    u_x = first_derivatives[:, 1:2]

    second_derivatives = torch.autograd.grad(
        outputs=u_x, inputs=tx,
        grad_outputs=torch.ones_like(u_x),
        create_graph=True,
    )[0]

    u_xx = second_derivatives[:, 1:2]
    residual = u_t + u * u_x - NU * u_xx
    return residual

# ============================================================
# 6. TRAIN THE PINN (ADAM + L-BFGS)
# ============================================================

def train():
    model = BurgersPINN().to(device=DEVICE, dtype=DTYPE)

    # 1. Setup Adam Optimizer
    optimizer_adam = torch.optim.Adam(model.parameters(), lr=LEARNING_RATE)

    (tx_f, tx_ic, u_ic, tx_bc, u_bc) = generate_training_points()
    history = []
    start_time = time.time()

    print(f"\nStarting Phase 1: Adam Optimization ({ADAM_STEPS} steps)...")
    for step in range(1, ADAM_STEPS + 1):
        optimizer_adam.zero_grad(set_to_none=True)

        residual = burgers_residual(model, tx_f)
        loss_pde = torch.mean(residual ** 2)

        prediction_ic = model(tx_ic)
        loss_ic = torch.mean((prediction_ic - u_ic) ** 2)

        prediction_bc = model(tx_bc)
        loss_bc = torch.mean((prediction_bc - u_bc) ** 2)

        loss_total = loss_pde + loss_ic + loss_bc
        loss_total.backward()
        optimizer_adam.step()

        if step % LOG_EVERY == 0 or step == 1 or step == ADAM_STEPS:
            history.append([step, loss_total.item(), loss_pde.item(), loss_ic.item(), loss_bc.item()])
            print(f"Adam Step {step:5d} | Total {loss_total.item():.4e} | PDE {loss_pde.item():.4e} | IC {loss_ic.item():.4e} | BC {loss_bc.item():.4e}")

    # 2. Setup L-BFGS Optimizer (The new addition)
    print(f"\nStarting Phase 2: L-BFGS Optimization ({LBFGS_STEPS} max steps)...")

    optimizer_lbfgs = torch.optim.LBFGS(
        model.parameters(),
        lr=1.0,
        max_iter=LBFGS_STEPS,
        max_eval=LBFGS_STEPS,
        tolerance_grad=1e-7,
        tolerance_change=1e-9,
        history_size=50,
        line_search_fn="strong_wolfe"
    )

    lbfgs_step_counter = 0

    # L-BFGS requires a closure function that evaluates the loss and gradients
    def closure():
        nonlocal lbfgs_step_counter
        optimizer_lbfgs.zero_grad(set_to_none=True)

        residual = burgers_residual(model, tx_f)
        loss_pde = torch.mean(residual ** 2)

        prediction_ic = model(tx_ic)
        loss_ic = torch.mean((prediction_ic - u_ic) ** 2)

        prediction_bc = model(tx_bc)
        loss_bc = torch.mean((prediction_bc - u_bc) ** 2)

        loss_total = loss_pde + loss_ic + loss_bc
        loss_total.backward()

        lbfgs_step_counter += 1
        current_step = ADAM_STEPS + lbfgs_step_counter

        if current_step % LOG_EVERY == 0 or lbfgs_step_counter == 1:
            history.append([current_step, loss_total.item(), loss_pde.item(), loss_ic.item(), loss_bc.item()])
            print(f"L-BFGS Step {current_step:5d} | Total {loss_total.item():.4e} | PDE {loss_pde.item():.4e} | IC {loss_ic.item():.4e} | BC {loss_bc.item():.4e}")

        return loss_total

    # Run L-BFGS
    optimizer_lbfgs.step(closure)

    elapsed = time.time() - start_time

    # Save model and configuration
    model_path = RESULTS_DIR / "burgers_vanilla_lbfgs_model.pt"
    torch.save({
        "model_state_dict": model.state_dict(),
        "width": WIDTH,
        "depth": DEPTH,
        "nu": NU,
        "adam_steps": ADAM_STEPS,
        "lbfgs_steps": LBFGS_STEPS,
        "N_F": N_F,
    }, model_path)

    # Save and Plot Loss History
    history_array = np.asarray(history, dtype=np.float64)
    history_path = RESULTS_DIR / "training_history_lbfgs.csv"
    np.savetxt(history_path, history_array, delimiter=",", header="step,total_loss,pde_loss,ic_loss,bc_loss", comments="")

    plt.figure(figsize=(8, 5))
    for column, label in zip(range(1, 5), ["Total", "PDE", "IC", "BC"]):
        plt.semilogy(history_array[:, 0], np.maximum(history_array[:, column], 1e-16), label=label)

    # Add a vertical line showing where Adam ends and L-BFGS begins
    plt.axvline(x=ADAM_STEPS, color='k', linestyle='--', label='L-BFGS Start')

    plt.xlabel("Training step")
    plt.ylabel("Mean squared error loss")
    plt.title("Vanilla Burgers PINN (Adam + L-BFGS): Training losses")
    plt.legend()
    plt.tight_layout()
    loss_plot = RESULTS_DIR / "training_losses_lbfgs.png"
    plt.savefig(loss_plot, dpi=200)
    plt.show()
    plt.close()

    print(f"\nTraining time: {elapsed:.2f} seconds")
    return model

