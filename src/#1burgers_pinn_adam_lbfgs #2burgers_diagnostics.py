def evaluate_reference(model):
    try:
        dataset_path = ensure_reference_dataset()
    except Exception as exc:
        print("\nReference evaluation skipped.")
        return

    with np.load(dataset_path, allow_pickle=False) as data:
        x = np.asarray(data["x"]).reshape(-1)
        t = np.asarray(data["t"]).reshape(-1)
        usol_raw = np.asarray(data["usol"])

    if usol_raw.shape == (len(x), len(t)):
        u_reference = usol_raw.T
    elif usol_raw.shape == (len(t), len(x)):
        u_reference = usol_raw

    X, T = np.meshgrid(x, t, indexing="xy")
    tx_eval = np.column_stack((T.ravel(), X.ravel()))

    model.eval()
    predictions = []
    with torch.no_grad():
        chunk_size = 8192
        for start in range(0, tx_eval.shape[0], chunk_size):
            tx_chunk = torch.as_tensor(tx_eval[start:start + chunk_size], dtype=DTYPE, device=DEVICE)
            predictions.append(model(tx_chunk).cpu().numpy())

    u_prediction = np.concatenate(predictions, axis=0).reshape(len(t), len(x))
    error = u_prediction - u_reference

    reference_l2 = np.linalg.norm(u_reference.ravel())
    reference_linf = np.max(np.abs(u_reference))

    relative_l2 = np.linalg.norm(error.ravel()) / reference_l2
    relative_linf = np.max(np.abs(error)) / reference_linf
    max_absolute_error = np.max(np.abs(error))

    print("\n===== REFERENCE EVALUATION =====")
    print(f"Relative L2 error:      {relative_l2:.6e}")
    print(f"Relative Linf error:    {relative_linf:.6e}")
    print(f"Maximum absolute error: {max_absolute_error:.6e}")

    # Compare spatial profiles at the last reference time (t=0.99)
    final_index = int(np.argmax(t))
    plt.figure(figsize=(8, 5))
    plt.plot(x, u_reference[final_index], label="Reference")
    plt.plot(x, u_prediction[final_index], "--", label="Vanilla PINN (L-BFGS)")
    plt.xlabel("x")
    plt.ylabel("u(x,t)")
    plt.title(f"Solution comparison at t = {t[final_index]:.2f}")
    plt.legend()
    plt.tight_layout()
    plt.savefig(RESULTS_DIR / "reference_comparison_final_time_lbfgs.png", dpi=200)
    plt.show()
    plt.close()

    # Absolute Error Field
    plt.figure(figsize=(8, 5))
    plt.imshow(np.abs(error), origin="lower", aspect="auto", extent=[x.min(), x.max(), t.min(), t.max()])
    plt.colorbar(label="Absolute error")
    plt.xlabel("x")
    plt.ylabel("t")
    plt.title("Vanilla Burgers (L-BFGS): Absolute error field")
    plt.tight_layout()
    plt.savefig(RESULTS_DIR / "absolute_error_field_lbfgs.png", dpi=200)
    plt.show()
    plt.close()

