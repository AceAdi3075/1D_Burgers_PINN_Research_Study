if not MODEL_PATH.exists():
    raise FileNotFoundError(f"Trained model not found at {MODEL_PATH}. Run B1 first.")

model = BurgersPINN().to(device=DEVICE, dtype=DTYPE)
checkpoint = torch.load(MODEL_PATH, map_location=DEVICE, weights_only=True)
model.load_state_dict(checkpoint["model_state_dict"])
model.eval()
print(f"Successfully loaded trained Vanilla PINN (L-BFGS).")

# ============================================================
# 4. DIAGNOSTIC GRID GENERATION
# ============================================================
# Load reference grid to align diagnostic points
with np.load(REFERENCE_PATH, allow_pickle=False) as data:
    x_ref = np.asarray(data["x"]).reshape(-1)
    t_ref = np.asarray(data["t"]).reshape(-1)
    usol_raw = np.asarray(data["usol"])

if usol_raw.shape == (len(x_ref), len(t_ref)):
    u_reference = usol_raw.T
else:
    u_reference = usol_raw

T_grid, X_grid = np.meshgrid(t_ref, x_ref, indexing="ij")

# Convert to torch tensors with requires_grad=True for continuous residual calculation
t_diag = torch.tensor(T_grid.flatten()[:, None], dtype=DTYPE, device=DEVICE).requires_grad_(True)
x_diag = torch.tensor(X_grid.flatten()[:, None], dtype=DTYPE, device=DEVICE).requires_grad_(True)
tx_diag = torch.cat([t_diag, x_diag], dim=1)

# Inverse X for Symmetry Check (u(-x, t))
x_inv_diag = -x_diag
tx_inv_diag = torch.cat([t_diag, x_inv_diag], dim=1)

# ============================================================
# 5. CALCULATE DIAGNOSTICS (RESIDUAL & SYMMETRY)
# ============================================================
print("Calculating dense continuous PDE residual and symmetry errors...")

# Predict standard u(t, x)
u_pred = model(tx_diag)

# Predict inverted u(t, -x)
u_pred_inv = model(tx_inv_diag)

# Calculate Symmetry Error: u(x,t) + u(-x,t) = 0
sym_error = torch.abs(u_pred + u_pred_inv).detach().cpu().numpy().reshape(len(t_ref), len(x_ref))

# Autodiff for PDE Residual
first_derivatives = torch.autograd.grad(outputs=u_pred, inputs=tx_diag, grad_outputs=torch.ones_like(u_pred), create_graph=True)[0]
u_t = first_derivatives[:, 0:1]
u_x = first_derivatives[:, 1:2]

second_derivatives = torch.autograd.grad(outputs=u_x, inputs=tx_diag, grad_outputs=torch.ones_like(u_x), create_graph=False)[0]
u_xx = second_derivatives[:, 1:2]

# R_theta = u_t + u * u_x - nu * u_xx
residual = (u_t + u_pred * u_x - NU * u_xx).detach().cpu().numpy().reshape(len(t_ref), len(x_ref))
u_pred_np = u_pred.detach().cpu().numpy().reshape(len(t_ref), len(x_ref))
error_to_ref = np.abs(u_pred_np - u_reference)

